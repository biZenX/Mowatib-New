class I18nService {
  constructor(initialLang = 'ar') {
    this.currentLang = initialLang;
  }

  setLanguage(lang) {
    if (translations[lang]) {
      this.currentLang = lang;
      document.documentElement.lang = lang;
      document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    }
  }

  t(key, ...params) {
    const dict = translations[this.currentLang] || translations.ar;
    let text = dict[key] || translations.en[key] || key;

    if (params && params.length > 0) {
      params.forEach((val, idx) => {
        text = text.replace(`{${idx}}`, val);
      });
    }
    return text;
  }

  isRTL() {
    return this.currentLang === 'ar';
  }

  formatMinutes(minutes) {
    if (minutes < 60) return `${minutes} ${this.t('min')}`;
    const h = (minutes / 60).toFixed(1);
    return `${h} ${this.t('hours')}`;
  }
}

export const i18n = new I18nService('ar');
